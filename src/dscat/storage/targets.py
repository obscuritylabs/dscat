"""Fully serialized typed target artifacts precede every publication transaction."""

import hashlib
from typing import TYPE_CHECKING, Annotated, Self

from pydantic import Field, model_validator

from dscat.export.dcat_us_3 import project_dcat, serialize_dcat
from dscat.export.loss import ProjectionLoss
from dscat.export.odcs_3_2 import project_odcs, serialize_odcs
from dscat.intake.limits import DEFAULT_LIMITS, fail
from dscat.models.base import StrictModel, Target
from dscat.models.diagnostics import TargetReadiness
from dscat.public_projection import (
    PublicProjection,
    public_dcat_bytes,
    public_odcs_bytes,
)
from dscat.storage.models import ExportEntry, ProjectionEntry, export_path

if TYPE_CHECKING:
    from dscat.models.catalog import Catalog
    from dscat.models.configuration import ExportConfiguration

Content = Annotated[bytes, Field(min_length=1, max_length=32 * 1024**2)]


class InternalArtifact(StrictModel):
    """An internal path/identity and exact bounded bytes, never a placeholder."""

    entry: ExportEntry
    content: Content

    @model_validator(mode="after")
    def content_identity(self) -> Self:
        """Require the manifest entry to describe exactly these serialized bytes."""
        if hashlib.sha256(self.content).hexdigest() != self.entry.sha256:
            msg = "Internal target artifact content identity mismatch."
            raise ValueError(msg)
        return self


class PublicArtifact(StrictModel):
    """Only a public relative path and exact approved document bytes."""

    entry: ProjectionEntry
    content: Content

    @model_validator(mode="after")
    def content_identity(self) -> Self:
        """Require exact public bytes without embedding canonical input identities."""
        if hashlib.sha256(self.content).hexdigest() != self.entry.sha256:
            msg = "Public target artifact content identity mismatch."
            raise ValueError(msg)
        return self


class PreparedInternal(StrictModel):
    """Requested targets and actual successful artifacts remain distinguishable."""

    requested: Annotated[list[Target], Field(max_length=2)]
    readiness: list[TargetReadiness]
    artifacts: Annotated[list[InternalArtifact], Field(max_length=100001)]
    losses: Annotated[list[ProjectionLoss], Field(max_length=10000)]

    @model_validator(mode="after")
    def exact_selection(self) -> Self:
        """Forbid duplicate targets and artifacts for blocked or unselected targets."""
        if (
            self.requested != sorted(set(self.requested))
            or [item.target for item in self.readiness] != self.requested
        ):
            msg = "Prepared target assessments must match the exact ordered selection."
            raise ValueError(msg)
        successful = {item.target for item in self.readiness if item.state == "ready"}
        paths = [item.entry.path for item in self.artifacts]
        if paths != sorted(set(paths)) or any(
            item.entry.target not in successful for item in self.artifacts
        ):
            msg = "Prepared target artifacts must be unique, ordered and successful."
            raise ValueError(msg)
        return self


def internal_artifact(
    target: Target, content: bytes, dataset_id: str | None = None
) -> InternalArtifact:
    """Bind generated bytes to a prescribed target path before filesystem writes."""
    entry = ExportEntry.model_validate(
        {
            "target": target,
            "path": export_path(target, dataset_id),
            "sha256": hashlib.sha256(content).hexdigest(),
        }
        | ({"dataset_id": dataset_id} if dataset_id is not None else {})
    )
    return InternalArtifact(entry=entry, content=content)


def prepare_targets(
    catalog: Catalog, configuration: ExportConfiguration, targets: list[Target]
) -> PreparedInternal:
    """Prepare ready internal targets while retaining explicit blocked assessments."""
    if len(set(targets)) != len(targets):
        raise fail(code="INVALID_INVOCATION")
    artifacts: list[InternalArtifact] = []
    readiness: list[TargetReadiness] = []
    losses: list[ProjectionLoss] = []
    for target in sorted(targets):
        if target == "dcat-us-3":
            projection = project_dcat(catalog, configuration)
            readiness.append(projection.readiness)
            losses.extend(projection.losses)
            if projection.readiness.state == "ready":
                if projection.document is None:
                    raise fail(code="INTERNAL_FAILURE")
                artifacts.append(
                    internal_artifact(target, serialize_dcat(projection.document))
                )
        else:
            odcs = project_odcs(catalog, configuration)
            readiness.append(odcs.readiness)
            losses.extend(odcs.losses)
            if odcs.readiness.state == "ready":
                if len(odcs.documents) != len(catalog.datasets):
                    raise fail(code="INTERNAL_FAILURE")
                artifacts.extend(
                    internal_artifact(target, serialize_odcs(document), record.id)
                    for record, document in zip(
                        catalog.datasets, odcs.documents, strict=True
                    )
                )
        if len(losses) > DEFAULT_LIMITS.diagnostics:
            raise fail(code="INPUT_LIMIT", limit="diagnostics")
    return PreparedInternal(
        requested=sorted(targets),
        readiness=readiness,
        artifacts=sorted(artifacts, key=lambda item: item.entry.path),
        losses=losses,
    )


def prepare_public_targets(projection: PublicProjection) -> list[PublicArtifact]:
    """Serialize only approved closed public documents, excluding private reports."""
    if any(item.state != "ready" for item in projection.readiness):
        raise fail(code="PUBLIC_PROJECTION_DENIED")
    contents: dict[str, bytes] = {}
    if projection.dcat is not None:
        contents[export_path("dcat-us-3")] = public_dcat_bytes(projection.dcat)
    for document in projection.odcs:
        # The public filename depends only on its approved emitted contract ID.
        path = export_path("odcs-3.2", document.id)
        if path in contents:
            raise fail(code="PUBLICATION_FAILURE")
        contents[path] = public_odcs_bytes(document)
    return [
        PublicArtifact(
            entry=ProjectionEntry(
                path=path, sha256=hashlib.sha256(content).hexdigest()
            ),
            content=content,
        )
        for path, content in sorted(contents.items())
    ]
